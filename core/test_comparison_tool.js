'use strict';
const assert = require('assert/strict'), fs = require('fs'), os = require('os'), path = require('path');
const { TOOLS, toOpenAITools } = require('./tools');
const { Sandbox } = require('./sandbox');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'xihe-comparison-tool-'));
(async () => {
  try {
    fs.writeFileSync(path.join(root, 'a.json'), '{"negative":336}');
    fs.writeFileSync(path.join(root, 'b.json'), '{"negative":252}');
    const side = { result_key: 'negative', unit: '个', definition: '背景负样本数', denominator: '84个正样本', time_origin: '不适用', dataset: 'B题样本v1', protocol: '固定抽样规则v1' };
    const manifest = { purpose: 'replication', source_result: { rel: 'a.json' }, replica_result: { rel: 'b.json' },
      metrics: [{ id: 'negative', value_type: 'count', source: side, replica: side, tolerance: { relative: 0.3 } }] };
    fs.writeFileSync(path.join(root, 'comparison.json'), JSON.stringify(manifest));
    const session = {}, ctx = { session, workspace: root, sandbox: new Sandbox(root) };
    assert(toOpenAITools({ effort: 'fast' }).some(t => t.function.name === 'result_compare'));
    const tool = TOOLS.find(t => t.name === 'result_compare');
    await tool.run(ctx, { manifest: 'comparison.json', id: 'q2' });
    assert.equal(session.comparison_reports.length, 1);
    const saved = session.comparison_reports[0];
    assert.equal(saved.record.summary.matches, 0);
    assert.equal(saved.record.metrics[0].relDiff, 0.25);
    const json = JSON.parse(fs.readFileSync(path.join(root, saved.json_rel), 'utf8'));
    assert.equal(json.metrics[0].classification, 'discrepancy');
    await assert.rejects(tool.run(ctx, { manifest: 'comparison.json', id: 'q2' }), /id已存在/);
    assert.equal(session.comparison_reports.length, 1, 'same report id cannot overwrite prior evidence');
    const { evidenceBlockers } = require('./delivery_evidence');
    assert(evidenceBlockers(root, session).some(s => s.includes('negative')), 'unresolved replication discrepancy blocks delivery');
    manifest.purpose = 'alternative';
    fs.writeFileSync(path.join(root, 'comparison.json'), JSON.stringify(manifest));
    await assert.rejects(tool.run(ctx, { manifest: 'comparison.json', id: 'unrelated', supersedes: [saved.json_rel], reason: '无关方案不能消掉原复算分歧' }), /保持比较目的/);
    const alternativeSession = {}, alternativeCtx = { ...ctx, session: alternativeSession };
    await tool.run(alternativeCtx, { manifest: 'comparison.json', id: 'q2-alternative' });
    fs.mkdirSync(path.join(root, 'paper'));
    fs.writeFileSync(path.join(root, 'paper', 'main.md'), '原稿将不同抽样误写为同口径一致。');
    const finding = TOOLS.find(t => t.name === 'review_finding');
    await finding.run(alternativeCtx, { op: 'register', id: 'q2-wording', claim: '比较口径表述不准确', kind: 'text', severity: 'must_fix', targets: [{ rel: 'paper/main.md', quote: '同口径一致' }] });
    assert(evidenceBlockers(root, alternativeSession).some(s => s.includes('q2-wording')));
    fs.writeFileSync(path.join(root, 'paper', 'main.md'), '修订为两套抽样方案差异，不视为复算通过。');
    await finding.run(alternativeCtx, { op: 'resolve', id: 'q2-wording', reason: '按规范对拍报告收束比较主张', revisions: [{ rel: 'paper/main.md', quote: '不视为复算通过' }], evidence: [{ rel: alternativeSession.comparison_reports[0].json_rel, quote: 'alternative_difference' }] });
    assert.deepEqual(evidenceBlockers(root, alternativeSession), []);
    fs.appendFileSync(path.join(root, 'paper', 'main.md'), '新修改');
    assert(evidenceBlockers(root, alternativeSession).some(s => s.includes('q2-wording')), 'subsequent manuscript changes reopen resolved finding');
    const independentCtx = { ...ctx, session: {} };
    manifest.purpose = 'replication';
    fs.writeFileSync(path.join(root, 'comparison.json'), JSON.stringify(manifest));
    await tool.run(independentCtx, { manifest: 'comparison.json', id: 'old-result' });
    assert(evidenceBlockers(root, independentCtx.session).length > 0);
    const failedReplacement = await tool.run(independentCtx, { manifest: 'comparison.json', id: 'still-different', supersedes: ['findings/comparisons/old-result.json'], reason: '再次复算但结果仍有差异' });
    assert.match(failedReplacement, /原报告未被替代/);
    assert.equal(independentCtx.session.comparison_reports.length, 2);
    assert(independentCtx.session.comparison_reports.every(r => r.status === 'active'), 'failed replacement and original both remain active evidence');
    const failedSaved = independentCtx.session.comparison_reports[1];
    assert(fs.existsSync(path.join(root, failedSaved.json_rel)), 'failed replacement has registered immutable files');
    assert(evidenceBlockers(root, independentCtx.session).some(s => s.includes('negative')));
    fs.writeFileSync(path.join(root, 'a.json'), '{"negative":252}');
    await assert.rejects(tool.run(independentCtx, { manifest: 'comparison.json', id: 'new-result', supersedes: ['findings/comparisons/old-result.json'] }), /reason/);
    await tool.run(independentCtx, { manifest: 'comparison.json', id: 'new-result', supersedes: ['findings/comparisons/old-result.json', failedSaved.json_rel], reason: '按已修订同口径结果重新对拍，旧报告保留为历史' });
    assert.equal(independentCtx.session.comparison_reports[0].status, 'superseded');
    assert(fs.existsSync(path.join(root, 'findings/comparisons/old-result.json')));
    assert.deepEqual(evidenceBlockers(root, independentCtx.session), [], 'explicitly superseded exploration must not block a current matching comparison');
    console.log('comparison tool and persisted registration: PASS');
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
