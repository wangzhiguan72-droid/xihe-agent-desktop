'use strict';
const assert = require('assert/strict');
const path = require('path');
const lib = require('./template_library');
const plans = require('./project_plan');
const profiles = require('./project_contest');
const app = path.resolve(__dirname, '..');
const profile = profiles.createProfile({ contest_kind: 'cumcm', edition: '2025', track: 'A', deadline: '2025-09-08T20:00:00+08:00' });
const before = plans.defaultPlan(profile);
before.skills.review = { mode: 'append', primary: 'xihe-research-methods', fallbacks: [] };
before.evidence.claim_trace = 'required';
const frozen = JSON.stringify(before);
assert(lib.list(app).some(row => row.id === 'apmcm'));
const sim = lib.apply(app, 'simulation', before, profile).plan;
assert.deepEqual(sim.contest, before.contest, 'method template preserves edition, track, rules and deadline');
assert.deepEqual(sim.skills.main, before.skills.main);
assert.equal(sim.skills.research.primary, 'pde-award-solve');
assert.deepEqual(sim.skills.review, before.skills.review);
assert.equal(sim.evidence.claim_trace, 'required');
assert.equal(JSON.stringify(before), frozen, 'preview never mutates saved plan');
const generic = lib.apply(app, 'generic', before, profile).plan;
assert.equal(generic.contest.contest_kind, 'generic');
assert.deepEqual(generic.contest.contest_rules, {});
assert.equal(generic.contest.deadline, null);
assert.equal(generic.contest.edition, 'unknown');
assert.equal(generic.contest.control_number, null);
assert.throws(() => lib.apply(app, '../bad', before, profile), /未找到模板/);
const same = lib.apply(app, 'cumcm', before, profile).plan;
assert.deepEqual(same.contest, before.contest, 'same contest keeps verified identity');
console.log('PASS template library: catalog, method/contest isolation, immutable previews, preserved review and trace');
