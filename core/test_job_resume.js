'use strict';
const assert = require('assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const resume = require('./job_resume');
const { createJobNotifications } = require('./job_notifications');

const session = () => ({ id: 's1', project_id: 'p1', data_epoch: 3, messages: [], status: 'running' });
const runningJob = { id: 'job_a', session_id: 's1', project_id: 'p1', status: 'running' };
const jobs = new Map([['job_a', runningJob]]);
const read = id => jobs.has(id) ? { meta: jobs.get(id), tail: 'execution output', stderr: '' } : null;

const s = session();
assert.throws(() => resume.registerWait(s, ['other'], read), /不存在/);
assert.throws(() => resume.registerWait({ ...s, id: 's2' }, ['job_a'], read), /会话/);
resume.registerWait(s, ['job_a'], read);
s.status = 'waiting_jobs';
assert.equal(resume.prepareWake(s, read), null, 'running work must not wake the main model');
jobs.set('job_a', { ...runningJob, status: 'succeeded' });
const ready = resume.prepareWake(s, read);
assert.match(ready.text, /succeeded/);
assert.match(ready.text, /不.*正式.*证据/);
assert.equal(s.job_wait.status, 'queued');
resume.claimWake(s);
assert.equal(s.job_wait.status, 'resuming');
assert.equal(s.job_wait.attempts, 1);
assert.throws(() => resume.claimWake(s), /认领/);
resume.recoverWait(s);
assert.equal(s.job_wait.status, 'queued', 'restart between model requests resumes from persisted history');
resume.claimWake(s);
s.messages.push({ role: 'assistant', tool_calls: [{ id: 'unknown_write', function: { name: 'fs_write' } }] });
s.pendingApproval = { id: 'unknown_write', tool: 'fs_write', summary: '写结果文件' };
resume.recoverWait(s);
assert.equal(s.job_wait.status, 'needs_review', 'unknown in-flight effects must not auto replay');
assert.equal(s.job_wait.interrupted_approval.tool, 'fs_write', 'interrupted approval is preserved for a concrete manual recovery action');

const changed = session(); resume.registerWait(changed, ['job_a'], read); changed.status = 'waiting_jobs'; changed.data_epoch++;
assert.equal(resume.prepareWake(changed, read), null);
assert.equal(changed.job_wait.status, 'needs_review');
const paused = session(); resume.registerWait(paused, ['job_a'], read); paused.status = 'waiting_input'; paused.pendingQuestion = { question: 'choose' };
assert.equal(resume.prepareWake(paused, read), null, 'must preserve pending human decisions');
const cancelled = session(); resume.registerWait(cancelled, ['job_a'], read); resume.cancelWait(cancelled);
assert.equal(resume.prepareWake(cancelled, read), null);
jobs.set('job_a', { ...runningJob, status: 'failed' });
const failed = session(); resume.registerWait(failed, ['job_a'], read); failed.status = 'waiting_jobs';
assert.match(resume.prepareWake(failed, read).text, /failed/, 'failed computation wakes master to inspect rather than fabricating success');
const beforeRequest = session(); resume.registerWait(beforeRequest, ['job_a'], read); beforeRequest.status = 'waiting_jobs';
resume.prepareWake(beforeRequest, read); const retryId = resume.claimWake(beforeRequest);
resume.finishWake(beforeRequest, retryId, { failed: true });
assert.equal(beforeRequest.job_wait.status, 'queued');
assert.equal(resume.prepareWake(beforeRequest, read), null, 'failed model requests back off before retry');
const afterWrite = session(); resume.registerWait(afterWrite, ['job_a'], read); afterWrite.status = 'waiting_jobs';
resume.prepareWake(afterWrite, read); const wroteId = resume.claimWake(afterWrite);
afterWrite.messages.push({ role: 'assistant', tool_calls: [{ id: 'wrote', function: { name: 'fs_write' } }] });
resume.finishWake(afterWrite, wroteId, { failed: true });
assert.equal(afterWrite.job_wait.status, 'needs_review', 'a model failure following side effects cannot silently retry');
const compacted = session(); resume.registerWait(compacted, ['job_a'], read); compacted.status = 'waiting_jobs';
compacted.messages = Array.from({ length: 20 }, () => ({ role: 'user', content: 'old history' }));
resume.prepareWake(compacted, read); const compactId = resume.claimWake(compacted);
compacted.job_wait.had_tools = true;
compacted.messages = [{ role: 'assistant', tool_calls: [{ id: 'after-compaction', function: { name: 'fs_write' } }] }];
resume.recoverWait(compacted);
assert.equal(compacted.job_wait.status, 'needs_review', 'compaction cannot hide unresolved tool calls behind a stale message index');
compacted.job_wait.status = 'resuming'; compacted.messages = [];
resume.finishWake(compacted, compactId, { failed: true });
assert.equal(compacted.job_wait.status, 'needs_review', 'durable tool-use marker survives compacted history on failure');
jobs.set('job_a', { ...runningJob, status: 'needs_review' });
const unknown = session(); resume.registerWait(unknown, ['job_a'], read); unknown.status = 'waiting_jobs';
assert.equal(resume.prepareWake(unknown, read), null); assert.equal(unknown.job_wait.status, 'needs_review');
resume.cancelWait(unknown);
assert.equal(unknown.job_wait.status, 'cancelled', 'manual continuation or stop clears a stale recovery card');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'xihe-job-notices-'));
try {
  const file = path.join(tmp, 'notices.json');
  const store = createJobNotifications(file);
  store.observe({ type: 'finish', job: { ...runningJob, status: 'succeeded', attempts: 1 } });
  store.observe({ type: 'finish', job: { ...runningJob, status: 'succeeded', attempts: 1 } });
  let snapshot = store.snapshot({ session_id: 's1' });
  assert.equal(snapshot.notifications.length, 1, 'duplicate finish or reconnect must not create duplicate notifications');
  assert.equal(snapshot.unread, 1);
  assert.equal(store.snapshot({ project_id: 'unrelated' }).notifications.length, 0);
  store.ack([snapshot.notifications[0].id]);
  assert.equal(createJobNotifications(file).snapshot({}).unread, 0, 'read status survives restart');
  store.observe({ type: 'finish', job: { ...runningJob, status: 'failed', attempts: 2 } });
  assert.equal(createJobNotifications(file).snapshot({}).unread, 1);
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
console.log('job parent resume and durable notifications passed');
