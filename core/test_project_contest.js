'use strict';
const assert = require('assert/strict');
const { createProfile, sessionFields } = require('./project_contest');
const p = createProfile({ contest_kind: 'mathorcup-bigdata', edition: '2026', stage: 'preliminary', track: 'B' });
assert.equal(p.revision, 1);
assert.deepEqual(createProfile({}, p), p, 'unchanged settings do not create a revision');
const a = sessionFields(p), b = sessionFields(p);
a.contest_identity.track = 'A'; a.contest_rules.source = 'changed';
assert.equal(b.contest_identity.track, 'B');
assert.equal(p.identity.track, 'B');
assert.deepEqual(p.rules, {});
assert(!('contest' in b) && !('paper_audit' in b));
assert.throws(() => createProfile({ contest_kind: 'missing' }), /未安装/);
assert.throws(() => createProfile({ contest_rules: [] }, p), /对象/);
assert.throws(() => createProfile({ deadline: 'invalid' }, p), /截止/);
assert.throws(() => createProfile({ contest_rules: { source: '本届原文', profile: 'mathorcup-bigdata-2026-preliminary', max_body_pages: 999 } }, p), /冲突/);
const changed = createProfile({ track: 'A' }, p);
assert.equal(changed.revision, 2);
assert.equal(sessionFields(changed).contest_identity.track, 'A');
const rules = { source: '本届格式PDF第2页及AI规定第3条', profile: 'mathorcup-bigdata-2026-preliminary', max_body_pages: 30,
  ai_statement_in_body: true, ai_statement_position: 'after_references', appendix_code_required: true };
const verified = createProfile({ contest_rules: rules, deadline: Date.now() + 3600000 }, p);
const controlOnly = createProfile({ control_number: '1234567' }, verified);
assert.equal(controlOnly.identity.control_number, '1234567');
assert.deepEqual(controlOnly.rules, verified.rules, 'adding a team control number in the same edition must not discard already registered rules');
assert.equal(controlOnly.revision, verified.revision + 1);
assert.throws(() => createProfile({ edition: '2027', contest_rules: rules }, verified), /年份冲突/);
const nextYear = createProfile({ edition: '2027' }, verified);
assert.deepEqual(nextYear.rules, {}, 'different edition must not inherit previous verified rules');
assert.equal(nextYear.deadline, null);
console.log('project contest snapshots: PASS');
