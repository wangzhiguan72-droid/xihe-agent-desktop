'use strict';
const assert = require('assert/strict');
const fs = require('fs'), os = require('os'), path = require('path');
const workflows = require('./contest_workflows');
const { buildSystem } = require('./agent');
const { installPaperTemplate } = require('./tools');
const { auditPaperTex } = require('./tools');
const { effectivePhase, phaseBlock } = require('./spiral');
const { usePaperProfile } = require('./contest_quality');
const app = path.resolve(__dirname, '..');
assert.equal(workflows.contestKind({ mode: 'math', title: 'CUMCM2026 A' }), 'cumcm');
assert.equal(workflows.contestKind({ mode: 'math', title: 'MathorCup 大数据竞赛 B' }), 'mathorcup-bigdata');
assert.equal(workflows.contestKind({ mode: 'math', title: 'MathorCup 数学建模挑战赛' }), 'generic');
assert.equal(workflows.contestKind({ contest_kind: 'generic', title: '妈妈杯' }), 'generic');
assert.equal(workflows.mathSkill('deepseek', { contest_kind: 'mathorcup-bigdata' }), 'my-mathorcup-bigdata');
assert.equal(workflows.mathSkill('glm', { contest_kind: 'mathorcup-bigdata' }), 'my-mathorcup-bigdata');
assert.equal(workflows.mathSkill('deepseek', { contest_kind: 'cumcm' }), 'my-cumcm-deepseek');
assert.equal(usePaperProfile({ contest_kind: 'mathorcup-bigdata', paper_profile: 'cumcm-user' }), false);
const lateMama = { mode: 'math', contest: true, contest_kind: 'mathorcup-bigdata', contest_start: 1, contest_deadline: 1000, contest_phase: 'baseline' };
assert.equal(effectivePhase(lateMama, 900), 'baseline', '国赛时长比例不能强推妈妈杯阶段');
assert.match(phaseBlock(lateMama, 900), /MathorCup.*阶段/);
assert.doesNotMatch(phaseBlock(lateMama, 900), /前 19%/);
const minimalMama = String.raw`\begin{document}\tableofcontents\section{问题重述}结果\begin{thebibliography}{9}\bibitem{a}来源2026\end{thebibliography}\section*{AI工具使用声明}如实说明\appendix\section{支撑材料}\end{document}`;
const options = { contestFit: true, contestKind: 'mathorcup-bigdata', rules: { source: '2026本届规则', ai_statement_in_body: true, max_body_pages: 30 }, pdf: { pages: 114, body_pages: 29, appendix_pages: 83, toc_pages: 1, kw_on_p1: true } };
let issues = auditPaperTex(minimalMama, options);
assert(!issues.some(s => /^【必须修/.test(s) && /AI|全文.*50|附录.*20|正文.*30/.test(s)), '妈妈杯不能沿用国赛AI顺序或总页数约束');
issues = auditPaperTex(minimalMama, { ...options, pdf: { ...options.pdf, body_pages: 31 } });
assert(issues.some(s => /^【必须修】正文 31 页/.test(s)));
assert.deepEqual(workflows.supportPolicy({ contest_kind: 'mathorcup-bigdata' }), { max_bytes: null });
assert.equal(workflows.supportPolicy({ contest_kind: 'mathorcup-bigdata', contest_rules: { source: '规则第4页', max_support_bytes: 50000000 } }).max_bytes, 50000000);
assert.deepEqual(workflows.supportPolicy({ contest_kind: 'mathorcup-bigdata', contest_rules: { max_support_bytes: 1 } }), { max_bytes: null });
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'xihe-mama-'));
try {
  installPaperTemplate(root, 'main.tex', { contest_kind: 'mathorcup-bigdata' });
  const tex = fs.readFileSync(path.join(root, 'main.tex'), 'utf8');
  assert.match(tex, /\\tableofcontents/);
  assert.doesNotMatch(tex, /cumcmthesis/);
  fs.writeFileSync(path.join(root, 'main.tex'), 'existing manuscript');
  installPaperTemplate(root, 'main.tex', { contest_kind: 'cumcm' });
  assert.equal(fs.readFileSync(path.join(root, 'main.tex'), 'utf8'), 'existing manuscript');
  const sys = buildSystem('math', root, {}, app, 'deepseek', null, { contest_kind: 'mathorcup-bigdata' });
  assert.match(sys, /已加载技能 my-mathorcup-bigdata/);
  assert.doesNotMatch(sys, /已加载技能 my-cumcm-/);
} finally { fs.rmSync(root, { recursive: true, force: true }); }
const { DEEP_APPENDIX, EXTREME_APPENDIX } = require('./modes');
assert(EXTREME_APPENDIX.includes(DEEP_APPENDIX.slice(DEEP_APPENDIX.indexOf('\n', 2))), 'extreme must really inherit deep techniques and cost discipline');
console.log('contest workflows: passed');
