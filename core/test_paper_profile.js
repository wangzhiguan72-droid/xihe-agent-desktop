'use strict';
const assert = require('assert/strict');
const { auditPaperTex, collectSourceFiles, TOOLS } = require('./tools');
const quality = require('./contest_quality');
assert.equal(quality.usePaperProfile({ mode: 'math' }), false);
assert.equal(quality.usePaperProfile({ mode: 'math', title: '普通回归研究' }), false);
assert.equal(quality.usePaperProfile({ mode: 'math', title: '研究生数学建模竞赛' }), false);
assert.equal(quality.usePaperProfile({ mode: 'math', title: 'MCM 2026 A' }), false);
assert.equal(quality.usePaperProfile({ mode: 'math', title: 'CUMCM2024B' }), true);
assert.equal(quality.usePaperProfile({ mode: 'math', paper_profile: 'generic' }), false);
const tex = String.raw`\begin{document}\begin{abstract}本文采用\textbf{整数规划模型}，总成本\textbf{100元}。\keywords{整数规划；车辆调度；成本控制}\end{abstract}\section{结果}结果如下。\end{document}`;
let result = auditPaperTex(tex, { contestFit: true, paperProfile: true, pdf: { pages: 35, body_pages: 31, kw_on_p1: true } });
assert(result.some(w => /^【必须修】/.test(w) && /31.*30/.test(w)), '本机国赛质量标准必须拦截正文31页');
result = auditPaperTex(tex, { contestFit: true, paperProfile: true, pdf: { pages: 40, body_pages: 25, appendix_pages: 14, kw_on_p1: true } });
assert(!result.some(w => /^【必须修】/.test(w) && /页.*30/.test(w)), '附录不能计入30页正文上限');
result = auditPaperTex(tex, { contestFit: true, paperProfile: true, pdf: { body_pages: 10 } });
assert(result.some(w => /^【必须修】正文.*10.*20/.test(w)), '正文低于20页不能通过新篇幅门禁');
result = auditPaperTex(tex + String.raw`\appendix\section{支撑材料}scripts/q1.py`, { contestFit: true, paperProfile: true, sourceFiles: ['scripts/q1.py'], pdf: { body_pages: 25 } });
assert(result.some(w => /^【必须修】附录缺关键代码/.test(w)), '只有文件列表还需展示关键算法步骤');
const excerpt = tex + String.raw`\appendix\section{支撑材料}\section{核心算法节选}\lstinputlisting[firstline=1,lastline=2]{../scripts/q1.py}`;
result = auditPaperTex(excerpt, { contestFit: true, paperProfile: true, sourceFiles: ['scripts/q1.py', 'scripts/plot.py'], pdf: { pages: 46, body_pages: 25, appendix_pages: 20 } });
assert(!result.some(w => /^【必须修】/.test(w) && /完整源程序|截取行范围|关键代码/.test(w)), '关键步骤允许节选，绘图源码无需全部进入附录');
result = auditPaperTex(excerpt, { contestFit: true, paperProfile: true, pdf: { pages: 47, body_pages: 25, appendix_pages: 21 } });
assert(result.some(w => /^【必须修】附录 21 页 > 20/.test(w)), '附录超过20页应拦截');
result = auditPaperTex(excerpt, { contestFit: true, paperProfile: true, pdf: { pages: 51, body_pages: 30, appendix_pages: 20 } });
assert(result.some(w => /^【必须修】全文 51 页 > 50/.test(w)), '摘要也占总页数，30+20+1不能通过');
result = auditPaperTex(excerpt, { contestFit: true, paperProfile: true, pdf: { pages: 50, body_pages: 29, appendix_pages: 20 } });
assert(!result.some(w => /^【必须修】(?:正文|附录|全文).*页/.test(w)), '正文29+附录20+摘要1应通过篇幅检查');
assert(result.some(w => /篇幅建议.*23—28/.test(w)), '正文29页应提示23—28页优先目标而非硬拒绝');
result = auditPaperTex(excerpt, { contestFit: true, paperProfile: true, pdf: { pages: 24, body_pages: 22, appendix_pages: 1 } });
assert(result.some(w => /篇幅建议.*23—28/.test(w)) && !result.some(w => /^【必须修】正文/.test(w)), '22页仅提示优先篇幅');
result = auditPaperTex(excerpt, { contestFit: true, paperProfile: true, pdf: { pages: 49, body_pages: 28, appendix_pages: 20 } });
assert(!result.some(w => /篇幅建议|^【必须修】(?:正文|附录|全文).*页/.test(w)), '正文28+附录20+摘要1满足全部篇幅条件');
const fs = require('fs'), os = require('os'), path = require('path'), crypto = require('crypto');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'xihe-paper-fresh-'));
try {
  fs.mkdirSync(path.join(root, 'scripts'));
  fs.mkdirSync(path.join(root, 'exp_repro', 'scripts'), { recursive: true });
  fs.writeFileSync(path.join(root, 'scripts', 'solve.py'), 'print(1)');
  fs.writeFileSync(path.join(root, 'exp_repro', 'scripts', 'solve.py'), 'print(1)');
  assert.deepEqual(collectSourceFiles(root, { source_files: ['exp_repro/scripts/solve.py'] }), ['scripts/solve.py'], '复现隔离副本不能重复当正式源码');
  fs.writeFileSync(path.join(root, 'main.tex'), 'current tex');
  fs.writeFileSync(path.join(root, 'main.pdf'), 'current pdf');
  fs.mkdirSync(path.join(root, 'paper'));
  fs.writeFileSync(path.join(root, 'paper', 'main.pdf'), 'current pdf');
  const { autoFinished, nextStepHint } = require('./agent');
  const unfinished = { mode: 'math', paper_profile: 'cumcm-user', contest: false, question_graph: [{ id: 1, status: 'committed' }] };
  assert.equal(autoFinished(unfinished, root), false, '普通国赛会话也不能仅凭PDF宣称完成');
  assert.match(nextStepHint(unfinished, root), /交付尚未完成/, '续推提示必须指出新的阻断项');
  const hash = file => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
  const a = { paper_contract_version: quality.PAPER_QUALITY_VERSION, tex_path: 'main.tex', pdf_path: 'main.pdf', tex_sha256: hash('main.tex'), pdf_sha256: hash('main.pdf') };
  a.inputs = require('./review_snapshot').paperInputs(root, a.tex_path);
  const s = { paper_audit: a, abstract_check: { src: 'main.tex', sha256: a.tex_sha256.slice(0, 16) } };
  assert.deepEqual(quality.paperAuditBlockers(root, s), []);
  assert(quality.paperAuditBlockers(root, { ...s, paper_audit: { ...a, paper_contract_version: 'old' } }).some(x => /契约已更新/.test(x)), '旧版验收不能跳过新附录与全文页数规则');
  fs.writeFileSync(path.join(root, 'main.tex'), 'modified tex');
  assert(quality.paperAuditBlockers(root, s).length > 0, '已改稿必须使旧审计失效');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
(async () => {
  const tool = TOOLS.find(t => t.name === 'abstract_check');
  const ctx = { session: { mode: 'math', paper_profile: 'cumcm-user' } };
  const out = await tool.run(ctx, { text: String.raw`\begin{abstract}本文采用\textbf{整数规划模型}处理调度。\keywords{整数规划；车辆调度}\end{abstract}` });
  assert(/3.?5|3—5/.test(out) && ctx.session.abstract_check.must_fix > 0, '真实工具入口必须执行关键词数量规则');
  console.log('PASS paper profile integration');
})().catch(e => { console.error(e); process.exitCode = 1; });
