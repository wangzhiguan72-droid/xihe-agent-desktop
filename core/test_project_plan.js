'use strict';
const assert = require('assert/strict');
const fs = require('fs'), os = require('os'), path = require('path');
const skills = require('./skills'), plans = require('./project_plan');
const { buildSystem } = require('./agent');
const { executeTool } = require('./tools');
const { Sandbox } = require('./sandbox');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'xihe-plan-'));
const original = skills.ROOTS.slice();
const put = (app, name, content) => {
  const dir = path.join(app, 'skills', name); fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'SKILL.md'), `---\nname: ${name}\nversion: "1.0"\ndescription: fixture\n---\n${content}`);
  return dir;
};
(async () => {
  skills.ROOTS.splice(0);
  const app = path.join(temp, 'computer-one'), target = path.join(temp, 'computer-two');
  put(app, 'contest-modeling-generic', 'GENERIC_MAIN');
  const method = put(app, 'method', 'METHOD_V1');
  fs.mkdirSync(path.join(method, 'scripts'));
  fs.writeFileSync(path.join(method, 'scripts/check.py'), 'print("FROZEN_SCRIPT_V1")');
  put(target, 'contest-modeling-generic', 'DIFFERENT_MAIN');
  put(target, 'method', 'LOCAL_V99');
  const plan = plans.defaultPlan();
  assert.equal(plan.evidence.claim_trace, 'optional');
  plan.skills.research = { mode: 'replace', primary: 'not-installed', fallbacks: ['method'] };
  plan.evidence.claim_trace = 'required';
  const normalized = plans.normalizePlan(plan);
  assert.equal(plans.sessionFields(normalized).claim_trace_required, true);
  const effective = plans.resolvePlan({ appDir: app, plan: normalized });
  assert.equal(effective.entries[1].name, 'method'); assert(effective.entries[1].fallbacks.length);
  const pack = plans.exportPackage({ appDir: app, plan: normalized });
  assert(!JSON.stringify(pack).includes(temp), 'portable package must not contain machine roots');
  const imported = plans.importPackage(pack, null, path.join(temp, 'project-two'));
  assert.equal(imported.plan.evidence.claim_trace, 'required');
  const mcmPlan = plans.normalizePlan({ ...normalized, contest: { contest_kind: 'mcm-icm', edition: '2027', control_number: '1234567' } });
  const mcmPack = plans.exportPackage({ appDir: app, plan: mcmPlan });
  const mcmImported = plans.importPackage(mcmPack, null, path.join(temp, 'mcm-project'));
  assert.equal(mcmImported.plan.contest.control_number, '1234567');
  assert.equal(plans.sessionFields(mcmImported.plan).contest_identity.control_number, '1234567');
  const frozen = plans.snapshot({ appDir: target, plan: imported.plan, options: { projectRoot: imported.assetRoot },
    lock: imported.lock, storageRoot: path.join(temp, 'project-two'), revision: 2 });
  const session = { ...plans.sessionFields(frozen.plan), mode: 'math', skill_plan_snapshot: frozen };
  assert.equal(session.claim_trace_required, true);
  assert.equal(frozen.plan.evidence.claim_trace, 'required');
  const prompt = buildSystem('math', temp, {}, target, 'deepseek', null, session);
  assert(prompt.includes('GENERIC_MAIN') && prompt.includes('METHOD_V1'));
  assert(!prompt.includes('LOCAL_V99') && !prompt.includes('DIFFERENT_MAIN'));
  assert(prompt.includes('替换主Skill') && prompt.includes('证据门禁'));
  assert(!plans.composedBlock(target, session, {}, text => text, ['review']).includes('METHOD_V1'), 'reviewer must not receive research replacement as its own directive');
  fs.writeFileSync(path.join(target, 'skills/method/SKILL.md'), 'LOCAL_V100');
  assert(plans.loadSessionSkill(target, session, 'method').content.includes('METHOD_V1'));
  const ctx = { appDir: target, session, settings: {}, workspace: temp, sandbox: new Sandbox(temp, { readOnlyRoots: [frozen.root] }) };
  const read = await executeTool(ctx, 'skill_load', { name: 'method' });
  assert(read.data.includes('METHOD_V1')); assert.equal(session.skill_reads[0].sha256, frozen.entries[1].sha256);
  assert.throws(() => ctx.sandbox.resolve(path.join(frozen.root, 'method/SKILL.md'), 'w'), /只读/);
  const external = path.join(temp, 'external-project'); fs.mkdirSync(external);
  const pyCtx = { ...ctx, workspace: external, sandbox: new Sandbox(external, { readOnlyRoots: [frozen.root] }), children: new Set() };
  const frozenScript = path.join(frozen.root, 'method/scripts/check.py');
  const executed = await executeTool(pyCtx, 'python_run', { code: 'exec(open(' + JSON.stringify(frozenScript.replace(/\\/g, '/')) + ',encoding="utf-8").read())', result_artifact: true });
  assert.equal(executed.ok, true, executed.data); assert(executed.data.includes('FROZEN_SCRIPT_V1'));
  const refused = await executeTool(pyCtx, 'python_run', { code: 'open(' + JSON.stringify(frozenScript.replace(/\\/g, '/')) + ',"w").write("changed")', result_artifact: true });
  assert.equal(refused.ok, false); assert(refused.data.includes('PermissionError'));
  const tampered = structuredClone(pack); tampered.skills[0].files[0].content = Buffer.from('fake').toString('base64');
  assert.throws(() => plans.importPackage(tampered, null, path.join(temp, 'bad-import')), /指纹/);
  fs.appendFileSync(path.join(frozen.root, 'method/SKILL.md'), 'changed');
  assert.throws(() => plans.loadSessionSkill(target, session, 'method'), /快照内容已变化/);
  const bad = structuredClone(plan); bad.skills.research.mode = 'execute';
  assert.throws(() => plans.normalizePlan(bad), /mode/);
  const oldPlan = structuredClone(plan); delete oldPlan.evidence;
  assert.equal(plans.normalizePlan(oldPlan).evidence.claim_trace, 'optional');
  assert.equal(plans.sessionFields(plans.normalizePlan(oldPlan)).claim_trace_required, false);
  assert.throws(() => plans.normalizePlan({ ...plan, evidence: { claim_trace: 'unchecked' } }), /claim_trace/);
  assert.throws(() => plans.normalizePlan({ ...plan, evidence: { claim_trace: 'required', skip_run: true } }), /未知证据选项/);
  assert.throws(() => plans.normalizePlan({ ...plan, schema_version: 99 }), /schema_version/);
  console.log('PASS project plan: composition, fallback, portable lock vs local names, frozen session, evidence rules, tools, read-only/tamper');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => {
  skills.ROOTS.splice(0, skills.ROOTS.length, ...original);
  assert.equal(path.dirname(path.resolve(temp)), path.resolve(os.tmpdir())); fs.rmSync(temp, { recursive: true, force: true });
});
