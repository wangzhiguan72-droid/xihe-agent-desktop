assert.equal(resolveReasoning({ reasoning_effort: 'off' }, 'deepseek', provider, 'deepseek-flash').options.reasoningBody.thinking.type, 'disabled');
assert.equal(resolveReasoning({ model_reasoning: { 'deepseek:deepseek-flash': 'provider_default' }, reasoning_effort: 'off' }, 'deepseek', provider, 'deepseek-flash').options.reasoningBody, undefined);
assert.equal(resolveReasoning({ model_reasoning: { 'glm:m': 'high' } }, 'glm', { kind: 'anthropic' }, 'm').error != null, true);
assert.throws(() => normalizeModelReasoning({ 'relay:gpt-test': 'ultra' }), /档位/);
assert.equal(normalizeModelReasoning({ 'relay:gpt-test': 'max' })['relay:gpt-test'], 'max');
assert.throws(() => normalizeModelReasoning([]), /对象/);
assert.equal(reasoningProbeTimeout({requested:'low'}),120000);
assert.equal(reasoningProbeTimeout({requested:'high'}),120000);
assert.equal(reasoningProbeTimeout({requested:'max'}),180000);
