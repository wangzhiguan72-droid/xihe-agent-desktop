'use strict';
const assert = require('assert/strict');
const { resolveReasoning, callWithReasoning, normalizeModelReasoning, reasoningProbeTimeout, normalizeReasoningLimits, reasoningCapabilities } = require('./reasoning');
const provider = { kind: 'openai' };
const settings = { model_reasoning: { 'relay:gpt-test': 'medium', 'gpt-test': 'high' }, reasoning_effort: 'off' };
