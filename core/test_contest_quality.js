'use strict';
const assert = require('assert');
const { auditPaperTex } = require('./tools');
const tex = '\\begin{document}\\begin{abstract}给出可行方案\\end{abstract}\\section{问题一}解析结论如下。\\[x=1\\]\\end{document}';
const generic = auditPaperTex(tex, { contestFit: true, pdf: { pages: 34, body_pages: 33, kw_on_p1: true } });
assert(!generic.some(s => /^【必须修/.test(s) && /没有结果图|未编号行间公式|缺 AI|缺.*附录|30 页/.test(s)), '通用写作建议不得变成强制门禁');
assert(!generic.some(s => /2026.*规定|2026.*规范/.test(s)), '未知年份不能套2026规范');
const explicit = auditPaperTex(tex, { contestFit: true, rules: { source: '用户提供的当届规范第3条', max_body_pages: 30, ai_statement_in_body: true, appendix_code_required: true }, pdf: { pages: 34, body_pages: 33, kw_on_p1: true } });
assert(explicit.some(s => /^【必须修/.test(s) && /33.*30/.test(s)));
assert(explicit.some(s => /^【必须修/.test(s) && /AI/.test(s)));
const { contestWritingBlock } = require('./contest_quality');
const shortLimit = auditPaperTex(tex, { contestFit: true, rules: { source: '指定规则', max_body_pages: 20 }, pdf: { body_pages: 25 } });
assert(shortLimit.some(s => /^【必须修】正文 25 页 > 20/.test(s)), '小于旧模板30页的适用限制也须生效');
const { fileSizeWarning } = require('./contest_quality');
assert.equal(fileSizeWarning(21000000, {}), null);
assert.match(fileSizeWarning(2000, { source: '指定规则', max_file_bytes: 1000 }), /^【必须修】/);
assert.equal(fileSizeWarning(2000, { source: '指定规则', max_file_bytes: 3000 }), null);
assert(/基线/.test(contestWritingBlock()));
assert(/不.*数量|不.*凑/.test(contestWritingBlock()));
assert(/题目/.test(contestWritingBlock()));
assert(/题面.*参考文献|随题附件.*参考文献/.test(contestWritingBlock()));
assert(/综述|新颖性/.test(contestWritingBlock()));
const suppliedTex = String.raw`\begin{document}\section{问题一}按题目第2页及附件1第3列计算。\cite{problem}\begin{thebibliography}{9}\bibitem{problem} 2025年A题竞赛题目及随题附件1[EB/OL].\end{thebibliography}\end{document}`;
assert(auditPaperTex(suppliedTex, { contestFit: true }).some(x => /^【待人工核验】/.test(x) && /题面|随题材料/.test(x)), '通用数模TeX审计提示核实题面入文献表');
assert(!auditPaperTex(suppliedTex, { contestFit: true, rules: { source: '当届规则第5条', problem_materials_in_references: true } }).some(x => /题面|随题材料/.test(x)), '有来源的当届例外不误拦');
console.log('PASS contest writing advice is conditional; explicit rules and factual defects retain gates');
